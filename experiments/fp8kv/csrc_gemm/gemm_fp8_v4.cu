// fp8-weight GEMM on C500 -- v4. Staging is the bottleneck, not the MMA.
//
// diag_split.cu decomposed the v3 kernel on gate_up (12288x2048):
//     staging only   0.172 ms   (147 GB/s)
//     MMA body       0.022 ms
//     full           0.276 ms
// so 62% of the time is global->smem, and the bf16 MMA peak (149 TFLOPS, measured
// in mma_peak2.cu) is never approached. Three things were wrong with staging:
//
//  1. It converted fp8->bf16 on the way into smem, i.e. 37.6M conversions per
//     call -- 64xK of A re-converted by every block, which is 12x more work than
//     the MMA actually consumes (3.1M fragment values). Fix: stage RAW fp8 (also
//     halves smem) and convert at fragment-read time from a 256-entry LUT.
//  2. 8-byte loads. Fix: 16-byte loads.
//  3. One barrier per chunk with no overlap. Fix: double buffer -- issue the next
//     chunk's global loads into registers BEFORE the MMA loop, store them after.
//
// The LUT is exact for all 256 e4m3 encodings (incl. subnormals), generated by
// PyTorch and embedded via lut_e4m3_bf16.inc, so accuracy does not regress from
// the earlier subnormal-flush workaround. It lives in smem (uniform 512 B).
//
// Fragment layout unchanged and re-verified here (see csrc/calib.cu):
//     A : row = lane%16, k = {g*4+0..3}
//     B : n   = lane%16, k = same
//     C : row = lane%16, col = g*4 + reg          g = lane/16, warpSize = 64

#include <mc_runtime.h>
#include <cstdint>

typedef __NATIVE_VECTOR__(2, uint32_t) v2u;
typedef __NATIVE_VECTOR__(4, uint32_t) v4u;
typedef __NATIVE_VECTOR__(4, float) v4f;

// exact e4m3 (e4m3fn) -> bf16, 256 entries, generated with PyTorch
static __device__ __constant__ unsigned short kLutHost[256] = {
#include "lut_e4m3_bf16.inc"
};

template <int WPB, int KC, int NT, int PAD>
__global__ void gemm_v4_kernel(const uint8_t* __restrict__ A,
                               const uint8_t* __restrict__ Bn,
                               float* __restrict__ C,
                               int M, int N, int K) {
  constexpr int RS = KC + PAD;              // fp8 row stride in smem, bytes
  constexpr int BROWS = WPB * NT * 16;
  constexpr int NTHR = WPB * 64;
  constexpr int KSTEPS = KC / 16;
  constexpr int NPFA = 64 * KC / (NTHR * 16);
  constexpr int NPFB = BROWS * KC / (NTHR * 16);
  static_assert(NPFA >= 1 && NPFB >= 1, "chunk too small for 16B prefetch");

  __shared__ uint8_t sA[2][64 * RS];
  __shared__ uint8_t sB[2][BROWS * RS];
  __shared__ unsigned short lut[256];

  const int tid = threadIdx.x;
  const int warp = tid >> 6;
  const int lane = tid & 63;
  const int row = lane % 16;
  const int g = lane / 16;

  const int n0 = blockIdx.x * (WPB * NT * 16);
  if (n0 >= N) return;

  for (int i = tid; i < 256; i += NTHR) lut[i] = kLutHost[i];

  v4f acc[NT][4];
#pragma unroll
  for (int t = 0; t < NT; ++t)
#pragma unroll
    for (int m = 0; m < 4; ++m) acc[t][m] = v4f{0.f, 0.f, 0.f, 0.f};

  v4u pa[NPFA], pb[NPFB];
  const int ai = tid * 16;
  const int bi = tid * 16;

  // ---- prologue: fetch chunk 0 straight into smem ----
  {
#pragma unroll
    for (int j = 0; j < NPFA; ++j) {
      const int r = (ai + j * NTHR * 16) / KC;
      const int c = (ai + j * NTHR * 16) - r * KC;
      v4u v;
      __builtin_memcpy(&v, A + (size_t)r * K + c, 16);
      __builtin_memcpy(sA[0] + r * RS + c, &v, 16);
    }
#pragma unroll
    for (int j = 0; j < NPFB; ++j) {
      const int r2 = (bi + j * NTHR * 16) / KC;
      const int c2 = (bi + j * NTHR * 16) - r2 * KC;
      v4u v;
      __builtin_memcpy(&v, Bn + (size_t)(n0 + r2) * K + c2, 16);
      __builtin_memcpy(sB[0] + r2 * RS + c2, &v, 16);
    }
    __syncthreads();
  }

  const int NCH = K / KC;
  for (int ch = 0; ch < NCH; ++ch) {
    const int cur = ch & 1, nxt = cur ^ 1;

    // ---- issue next chunk's loads before compute so they overlap ----
    if (ch + 1 < NCH) {
      const int k0 = (ch + 1) * KC;
#pragma unroll
      for (int j = 0; j < NPFA; ++j) {
        const int r = (ai + j * NTHR * 16) / KC;
        const int c = (ai + j * NTHR * 16) - r * KC;
        __builtin_memcpy(&pa[j], A + (size_t)r * K + k0 + c, 16);
      }
#pragma unroll
      for (int j = 0; j < NPFB; ++j) {
        const int r = (bi + j * NTHR * 16) / KC;
        const int c = (bi + j * NTHR * 16) - r * KC;
        __builtin_memcpy(&pb[j], Bn + (size_t)(n0 + r) * K + k0 + c, 16);
      }
    }

    // ---- bf16 MMA, k=16 per step; fp8->bf16 at fragment read ----
#pragma unroll
    for (int s = 0; s < KSTEPS; ++s) {
      const int kh = s * 16 + g * 4;
      v2u va0, va1, va2, va3;
#define FRAG(dst, buf, srow)                                                   \
  {                                                                            \
    uint32_t q;                                                                \
    __builtin_memcpy(&q, (buf) + (srow) * RS + kh, 4);                         \
    dst = {                                                                    \
        (uint32_t)(lut[q & 0xFF] | (lut[(q >> 8) & 0xFF] << 16)),              \
        (uint32_t)(lut[(q >> 16) & 0xFF] | (lut[(q >> 24) & 0xFF] << 16))};    \
  }
      FRAG(va0, sA[cur], 0 + row)
      FRAG(va1, sA[cur], 16 + row)
      FRAG(va2, sA[cur], 32 + row)
      FRAG(va3, sA[cur], 48 + row)
#pragma unroll
      for (int t = 0; t < NT; ++t) {
        v2u vb;
        FRAG(vb, sB[cur], warp * NT * 16 + t * 16 + row)
        acc[t][0] = __builtin_mxc_mma_16x16x16bf16(vb, va0, acc[t][0]);
        acc[t][1] = __builtin_mxc_mma_16x16x16bf16(vb, va1, acc[t][1]);
        acc[t][2] = __builtin_mxc_mma_16x16x16bf16(vb, va2, acc[t][2]);
        acc[t][3] = __builtin_mxc_mma_16x16x16bf16(vb, va3, acc[t][3]);
      }
#undef FRAG
    }

    // ---- commit prefetched chunk into the other buffer ----
    if (ch + 1 < NCH) {
#pragma unroll
      for (int j = 0; j < NPFA; ++j) {
        const int r = (ai + j * NTHR * 16) / KC;
        const int c = (ai + j * NTHR * 16) - r * KC;
        __builtin_memcpy(sA[nxt] + r * RS + c, &pa[j], 16);
      }
#pragma unroll
      for (int j = 0; j < NPFB; ++j) {
        const int r = (bi + j * NTHR * 16) / KC;
        const int c = (bi + j * NTHR * 16) - r * KC;
        __builtin_memcpy(sB[nxt] + r * RS + c, &pb[j], 16);
      }
    }
    __syncthreads();
  }

  const int col = g * 4;
#pragma unroll
  for (int t = 0; t < NT; ++t) {
    const int no = n0 + (warp * NT + t) * 16 + col;
    if (no >= N) continue;
    float* p;
    p = C + (size_t)(0 + row) * N + no;
    p[0] = acc[t][0][0]; p[1] = acc[t][0][1]; p[2] = acc[t][0][2]; p[3] = acc[t][0][3];
    p = C + (size_t)(16 + row) * N + no;
    p[0] = acc[t][1][0]; p[1] = acc[t][1][1]; p[2] = acc[t][1][2]; p[3] = acc[t][1][3];
    p = C + (size_t)(32 + row) * N + no;
    p[0] = acc[t][2][0]; p[1] = acc[t][2][1]; p[2] = acc[t][2][2]; p[3] = acc[t][2][3];
    p = C + (size_t)(48 + row) * N + no;
    p[0] = acc[t][3][0]; p[1] = acc[t][3][1]; p[2] = acc[t][3][2]; p[3] = acc[t][3][3];
  }
}

#define LAUNCH_V4(WPB, KC, NT)                                                 \
  do {                                                                         \
    const int per = (WPB) * (NT) * 16;                                         \
    const int tiles = (N + per - 1) / per;                                     \
    gemm_v4_kernel<WPB, KC, NT, 8>                                             \
        <<<tiles, (WPB) * 64, 0, (mcStream_t)stream>>>(A, Bn, C, M, N, K);     \
  } while (0)

extern "C" int launch_gemm_v4(const uint8_t* A, const uint8_t* Bn, float* C,
                              int M, int N, int K, int cfg, void* stream) {
  switch (cfg) {
    case 0: LAUNCH_V4(4, 64, 1); break;
    case 1: LAUNCH_V4(4, 64, 2); break;
    case 2: LAUNCH_V4(4, 128, 1); break;
    case 3: LAUNCH_V4(2, 64, 1); break;
    case 4: LAUNCH_V4(2, 128, 2); break;
    case 5: LAUNCH_V4(4, 64, 4); break;
    default: return -1;
  }
  return 0;
}
